/**
 * Generates src/content/pageMeta/{lang}.ts from scripts/meta-translations.mjs.
 *
 * The prerendered HTML carries a translated <title> and <meta description>, but
 * once React mounted, PageMeta replaced them with the English strings each page
 * passes — /bg/dashboard showed "Dashboard — The Storm Watcher" in the tab, and so
 * did any crawler that renders JS. These per-language modules let PageMeta keep
 * the translated text. Each is its own on-demand chunk, so a visitor downloads one
 * language instead of the whole 81 kB table.
 *
 * English is left out on purpose: English pages keep the titles they pass
 * themselves. Blog posts are left out too: BlogPost renders the post's own
 * translated title.
 *
 * Committed rather than built on the fly so nothing has to run before `vite dev`.
 * src/content/pageMeta.test.ts fails on drift — same arrangement as
 * scripts/generate-blog-metadata.mjs.
 *
 * Run: node scripts/generate-page-meta.mjs
 */

import { writeFileSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { META, ROUTES, LANG_CODES } from './meta-translations.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = join(__dirname, '..', 'src', 'content', 'pageMeta');

export const PAGE_META_LANGS = Object.keys(LANG_CODES).filter((lang) => lang !== 'en');

/** path → { title, description } for one language, app routes only. */
export function pageMetaFor(lang) {
  const table = {};
  for (const { path, slug } of ROUTES) {
    if (path.startsWith('/blog/')) continue;
    const entry = META[slug]?.[lang];
    if (entry) table[path] = { title: entry.title, description: entry.description };
  }
  return table;
}

export function pageMetaSource(lang) {
  const rows = Object.entries(pageMetaFor(lang))
    .map(([path, text]) => `  ${JSON.stringify(path)}: ${JSON.stringify(text)},`)
    .join('\n');
  return `// Generated by scripts/generate-page-meta.mjs from scripts/meta-translations.mjs — do not edit.
import type { PageMetaTable } from '../pageMeta';

const meta: PageMetaTable = {
${rows}
};

export default meta;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(OUT_DIR, { recursive: true });
  for (const lang of PAGE_META_LANGS) {
    writeFileSync(join(OUT_DIR, `${lang}.ts`), pageMetaSource(lang));
  }
  console.log(`Wrote ${PAGE_META_LANGS.length} files to src/content/pageMeta/`);
}
