/**
 * Generates src/data/blog/metadata.ts from the post files.
 *
 * The blog list page needs slug/title/description/date/category per language —
 * 11% of the post data. The other 89% is article bodies, and importing them all
 * to render a list of ten links cost /blog a 152 kB chunk. Metadata is split out
 * so the list page carries only what it renders and each article body is fetched
 * on demand (src/data/blog/loadPost.ts).
 *
 * Committed rather than built on the fly so nothing has to run before `vite dev`.
 * src/data/blog/blogMetadata.test.ts regenerates it and fails on any drift —
 * same arrangement as scripts/blog-translations.json.
 *
 * Run: node scripts/generate-blog-metadata.mjs
 */

import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { build } from 'esbuild';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');

export async function buildMetadataSource() {
  const result = await build({
    entryPoints: [join(ROOT, 'src', 'data', 'blog', 'index.ts')],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    write: false,
    logLevel: 'silent',
  });
  const dataUrl = 'data:text/javascript;base64,'
    + Buffer.from(result.outputFiles[0].text).toString('base64');
  const { blogPosts } = await import(dataUrl);

  const meta = blogPosts.map((post) => {
    const translations = {};
    for (const [lang, t] of Object.entries(post.translations ?? {})) {
      translations[lang] = { title: t.title, description: t.description };
    }
    return {
      slug: post.slug,
      title: post.title,
      description: post.description,
      date: post.date,
      readingTime: post.readingTime,
      category: post.category,
      coverEmoji: post.coverEmoji,
      ...(Object.keys(translations).length > 0 ? { translations } : {}),
    };
  });

  return `// GENERATED by scripts/generate-blog-metadata.mjs — do not edit by hand.
// Run \`node scripts/generate-blog-metadata.mjs\` after changing a post's title,
// description or translations. blogMetadata.test.ts fails if this drifts.
import type { BlogPostMeta } from './types';

export const blogMeta: BlogPostMeta[] = ${JSON.stringify(meta, null, 2)};
`;
}

// Only write when run directly, so the test can import the builder.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const source = await buildMetadataSource();
  const out = join(ROOT, 'src', 'data', 'blog', 'metadata.ts');
  writeFileSync(out, source, 'utf-8');
  console.log(`✓ ${out}`);
}
