#!/usr/bin/env python3
"""
Sync all locale files to be complete against en.ts.
Run from project root: python3 scripts/sync_all_locales.py
"""
import re, os

BASE = os.path.join(os.path.dirname(__file__), '..', 'src', 'locales')

def get_keys(lang):
    path = os.path.join(BASE, f'{lang}.ts')
    return set(re.findall(r"^\s+'([^']+)'\s*:", open(path).read(), re.MULTILINE))

def escape(v):
    return v.replace("\\", "\\\\").replace("'", "\\'")

def inject(lang, additions):
    path = os.path.join(BASE, f'{lang}.ts')
    content = open(path, encoding='utf-8').read()
    existing = get_keys(lang)
    lines = []
    for k, v in additions.items():
        if k not in existing:
            lines.append(f"  '{k}': '{escape(v)}',")
    if not lines:
        print(f"  [{lang}] nothing to add")
        return
    block = '\n'.join(lines)
    idx = content.rfind('\n};')
    new = content[:idx] + '\n' + block + content[idx:]
    open(path, 'w', encoding='utf-8').write(new)
    print(f"  [{lang}] +{len(lines)} keys")

